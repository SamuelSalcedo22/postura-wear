package com.posturawear.core.tokens.global

import androidx.compose.ui.unit.dp

/**
 * Tokens globales de espaciado (nivel 1), en una escala de 2 dp pensada para pantallas pequeñas.
 * Convención: `spacing.<paso>` → [GlobalSpacing.S4] = `spacing.4` = 8 dp.
 */
object GlobalSpacing {
    val S0 = 0.dp
    val S1 = 2.dp
    val S2 = 4.dp
    val S3 = 6.dp
    val S4 = 8.dp
    val S5 = 12.dp
    val S6 = 16.dp
    val S7 = 20.dp
    val S8 = 24.dp
    val S10 = 32.dp
    val S12 = 48.dp
}
